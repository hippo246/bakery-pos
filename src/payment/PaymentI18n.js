export class PaymentI18n {
  constructor() {
    this.currentLanguage = PaymentLanguages.ENGLISH;
    this.loadLanguage();
  }

  /**
   * Load language from localStorage
   */
  loadLanguage() {
    try {
      const saved = localStorage.getItem('cafeos_payment_language');
      if (saved && PaymentTranslations[saved]) {
        this.currentLanguage = saved;
      }
    } catch (error) {
      console.error('[PaymentI18n] Failed to load language:', error);
    }
  }

  /**
   * Save language to localStorage
   */
  saveLanguage() {
    try {
      localStorage.setItem('cafeos_payment_language', this.currentLanguage);
    } catch (error) {
      console.error('[PaymentI18n] Failed to save language:', error);
    }
  }

  /**
   * Set current language
   */
  setLanguage(language) {
    if (PaymentTranslations[language]) {
      this.currentLanguage = language;
      this.saveLanguage();
      console.log('[PaymentI18n] Language set to:', language);
    }
  }

  /**
   * Get current language
   */
  getLanguage() {
    return this.currentLanguage;
  }

  /**
   * Get translation for key
   */
  translate(key, fallback = null) {
    const translations = PaymentTranslations[this.currentLanguage];
    const translation = translations[key];
    
    if (translation) {
      return translation;
    }
    
    // Fallback to English
    const englishTranslation = PaymentTranslations[PaymentLanguages.ENGLISH][key];
    if (englishTranslation) {
      return englishTranslation;
    }
    
    return fallback || key;
  }

  /**
   * Get all translations for current language
   */
  getTranslations() {
    return PaymentTranslations[this.currentLanguage];
  }

  /**
   * Get available languages
   */
  getAvailableLanguages() {
    return Object.keys(PaymentTranslations).map(code => ({
      code,
      name: this.getLanguageName(code)
    }));
  }

  /**
   * Get language name
   */
  getLanguageName(code) {
    const names = {
      [PaymentLanguages.ENGLISH]: 'English',
      [PaymentLanguages.HINDI]: 'हिंदी (Hindi)',
      [PaymentLanguages.MARATHI]: 'मराठी (Marathi)',
      [PaymentLanguages.GUJARATI]: 'ગુજરાતી (Gujarati)',
      [PaymentLanguages.TAMIL]: 'தமிழ் (Tamil)',
      [PaymentLanguages.TELUGU]: 'తెలుగు (Telugu)',
      [PaymentLanguages.KANNADA]: 'ಕನ್ನಡ (Kannada)',
      [PaymentLanguages.MALAYALAM]: 'മലയാളം (Malayalam)',
      [PaymentLanguages.BENGALI]: 'বাংলা (Bengali)',
      [PaymentLanguages.PUNJABI]: 'ਪੰਜਾਬੀ (Punjabi)'
    };
    
    return names[code] || code;
  }

  /**
   * Detect browser language
   */
  detectBrowserLanguage() {
    const browserLang = navigator.language || navigator.userLanguage;
    const langCode = browserLang.split('-')[0];
    
    // Map browser language codes to our language codes
    const langMap = {
      'en': PaymentLanguages.ENGLISH,
      'hi': PaymentLanguages.HINDI,
      'mr': PaymentLanguages.MARATHI,
      'gu': PaymentLanguages.GUJARATI,
      'ta': PaymentLanguages.TAMIL,
      'te': PaymentLanguages.TELUGU,
      'kn': PaymentLanguages.KANNADA,
      'ml': PaymentLanguages.MALAYALAM,
      'bn': PaymentLanguages.BENGALI,
      'pa': PaymentLanguages.PUNJABI
    };
    
    const detectedLang = langMap[langCode];
    if (detectedLang && PaymentTranslations[detectedLang]) {
      this.setLanguage(detectedLang);
    }
  }

  /**
   * Format currency with locale
   */
  formatCurrency(amount, currency = 'INR') {
    const localeMap = {
      [PaymentLanguages.ENGLISH]: 'en-IN',
      [PaymentLanguages.HINDI]: 'hi-IN',
      [PaymentLanguages.MARATHI]: 'mr-IN',
      [PaymentLanguages.GUJARATI]: 'gu-IN',
      [PaymentLanguages.TAMIL]: 'ta-IN',
      [PaymentLanguages.TELUGU]: 'te-IN',
      [PaymentLanguages.KANNADA]: 'kn-IN',
      [PaymentLanguages.MALAYALAM]: 'ml-IN',
      [PaymentLanguages.BENGALI]: 'bn-IN',
      [PaymentLanguages.PUNJABI]: 'pa-IN'
    };
    
    const locale = localeMap[this.currentLanguage] || 'en-IN';
    
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: currency
    }).format(amount);
  }

  /**
   * Format date with locale
   */
  formatDate(date, options = {}) {
    const localeMap = {
      [PaymentLanguages.ENGLISH]: 'en-IN',
      [PaymentLanguages.HINDI]: 'hi-IN',
      [PaymentLanguages.MARATHI]: 'mr-IN',
      [PaymentLanguages.GUJARATI]: 'gu-IN',
      [PaymentLanguages.TAMIL]: 'ta-IN',
      [PaymentLanguages.TELUGU]: 'te-IN',
      [PaymentLanguages.KANNADA]: 'kn-IN',
      [PaymentLanguages.MALAYALAM]: 'ml-IN',
      [PaymentLanguages.BENGALI]: 'bn-IN',
      [PaymentLanguages.PUNJABI]: 'pa-IN'
    };
    
    const locale = localeMap[this.currentLanguage] || 'en-IN';
    
    return new Intl.DateTimeFormat(locale, options).format(date);
  }

  /**
   * Get RTL (Right-to-Left) direction
   * None of the Indian languages are RTL, but this is for future expansion
   */
  getTextDirection() {
    return 'ltr';
  }

  /**
   * Destroy the i18n instance
   */
  destroy() {
    console.log('[PaymentI18n] Destroyed');
  }
}

// Singleton instance
let paymentI18nInstance = null;

/**
 * Get the singleton payment i18n instance
 */
export function getPaymentI18n() {
  if (!paymentI18nInstance) {
    paymentI18nInstance = new PaymentI18n();
  }
  return paymentI18nInstance;
}

export default PaymentI18n;
